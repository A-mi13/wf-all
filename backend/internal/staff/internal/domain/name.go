package domain

import "unicode"

// Допустимые невидимые символы имени: ZWJ склеивает эмодзи-последовательности (единственный допустимый Cf),
// VS15/VS16 выбирают текстовое или эмодзи-представление — подмены текста они не дают. Прочие
// селекторы варианта (U+FE00–FE0D, U+E0100+) — отказ, как у isInvisible.
const (
	zwj  = 0x200D
	vs15 = 0xFE0E
	vs16 = 0xFE0F
)

// DisplayNameOK — отображаемое имя сотрудника без символов, которые подменяют или прячут текст в письмах,
// подписях подтверждений и журнале (M-3 финального ревью): управляющих (Cc — перевод строки, табуляция,
// NUL), форматирующих (Cf — bidi U+202A–202E и U+2066–2069, LRM/RLM, мягкий перенос, BOM, U+200B, теговые
// символы), разделителей строк и абзацев (Zl, Zp) и невидимых «пустых» символов — та же проверка
// isInvisible, что у домена почты (заполнители, пустой шрифт Брайля, селекторы варианта). Исключения —
// ZWJ (эмодзи из нескольких символов) и VS15/VS16 (представление эмодзи). Длину и пустоту проверяет вызывающий.
func DisplayNameOK(name string) bool {
	for _, r := range name {
		if r == zwj || r == vs15 || r == vs16 {
			continue
		}
		if unicode.Is(unicode.Cc, r) || unicode.Is(unicode.Zl, r) || unicode.Is(unicode.Zp, r) || isInvisible(r) {
			return false
		}
	}
	return true
}
